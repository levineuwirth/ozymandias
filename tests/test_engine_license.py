"""The engine's license: GPL-2.0-or-later with its permission for generated
websites, its notice naming its holder, and the FSF's text as published."""

from __future__ import annotations

import hashlib
import re
import unittest

from tests._helpers import ENGINE, engine_path

NOTICE = engine_path("LICENSE")
# https://www.gnu.org/licenses/old-licenses/gpl-2.0.txt
GPL_V2_SHA256 = "edaef632cbb643e4e7a221717a6c441a4c1a7c918e6e4d56debc3d8739b233f6"
RULE = "\n" + "-" * 72 + "\n\n"


class EngineLicense(unittest.TestCase):
    def test_the_cabal_file_declares_it_and_names_the_notice(self):
        cabal = next(ENGINE.glob("*.cabal")).read_text(encoding="utf-8")
        self.assertRegex(cabal, r"(?m)^license:\s+GPL-2\.0-or-later$")
        self.assertRegex(cabal, r"(?m)^license-file:\s+LICENSE$")

    def test_the_notice_grants_version_2_or_later_and_names_a_holder(self):
        head = NOTICE.read_text(encoding="utf-8").split(RULE)[0]
        self.assertRegex(head, r"(?m)^Copyright \(C\) \d{4} \S.*$")
        self.assertIn("either version 2 of the License, or\n(at your option) any later version.", head)

    def test_the_permission_covers_generated_websites_and_nothing_lifted_out(self):
        head = " ".join(NOTICE.read_text(encoding="utf-8").split(RULE)[0].split())
        self.assertIn("permission to convey a website generated by this program", head)
        self.assertIn("covers those parts only as parts of such a website", head)
        self.assertIn("another site generator, a theme, a template collection or an application", head)

    def test_the_license_text_is_the_fsf_s(self):
        text = NOTICE.read_bytes().split(RULE.encode(), 1)[1]
        self.assertEqual(hashlib.sha256(text).hexdigest(), GPL_V2_SHA256)


if __name__ == "__main__":
    unittest.main()
